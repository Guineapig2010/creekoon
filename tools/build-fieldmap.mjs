// Converts the kit's GeoJSON (USGS NHD Arroyo Trabuco line + the creator's field features)
// into a compact module for the in-game north-up Field Map.
//   node tools/build-fieldmap.mjs
import fs from 'node:fs';
const field = JSON.parse(fs.readFileSync('data/field_features.geojson', 'utf8'));
const regional = JSON.parse(fs.readFileSync('data/regional_creek.geojson', 'utf8'));
const r5 = (v) => Math.round(v * 1e5) / 1e5;
// Douglas-Peucker in degrees (fine at this latitude for display)
function simplify(pts, eps) {
  if (pts.length < 3) return pts;
  let maxD = 0, idx = 0;
  const [ax, ay] = pts[0], [bx, by] = pts[pts.length - 1];
  const dx = bx - ax, dy = by - ay, L = Math.hypot(dx, dy) || 1e-12;
  for (let i = 1; i < pts.length - 1; i++) {
    const d = Math.abs((pts[i][0] - ax) * dy - (pts[i][1] - ay) * dx) / L;
    if (d > maxD) { maxD = d; idx = i; }
  }
  if (maxD < eps) return [pts[0], pts[pts.length - 1]];
  return [...simplify(pts.slice(0, idx + 1), eps).slice(0, -1), ...simplify(pts.slice(idx), eps)];
}
const main = regional.features.filter((f) => /Trabuco/i.test(f.properties.gnis_name || '')).map((f) => simplify(f.geometry.coordinates, 0.00008).map(([x, y]) => [r5(x), r5(y)]));
const feats = field.features.map((f) => {
  const g = f.geometry;
  let coords;
  if (g.type === 'Point') coords = [r5(g.coordinates[0]), r5(g.coordinates[1])];
  else if (g.type === 'LineString') coords = g.coordinates.map(([x, y]) => [r5(x), r5(y)]);
  else coords = g.coordinates[0].map(([x, y]) => [r5(x), r5(y)]);
  const p = f.properties;
  return { type: g.type, key: p.key, name: p.name, note: p.note, stroke: p.stroke, accuracy: p.accuracy, source: p.source, group: p.group || null, code: p.code || null, coords };
});
const out = `// Generated by tools/build-fieldmap.mjs from data/*.geojson (WGS84 lon/lat). Do not edit.
// Regional line: USGS National Hydrography Dataset, Arroyo Trabuco (simplified for display).
// Field features: the creator's approximate traces, estimates and photo camera pins.
export const REGIONAL = ${JSON.stringify(main)};
export const FIELD = ${JSON.stringify(feats)};
`;
fs.writeFileSync('src/core/fieldmap.js', out);
console.log('regional lines', main.length, 'points', main.reduce((a, l) => a + l.length, 0), 'field features', feats.length, 'bytes', out.length);
